#!/usr/bin/env node
'use strict';
// Generates ../data.js and ../excluded.txt from IGDB + SteamSpy + Steam store.
//
// Usage (PowerShell):
//   $env:TWITCH_CLIENT_ID = '...'; $env:TWITCH_CLIENT_SECRET = '...'; npm run build-data
//
// Get credentials by registering an app at https://dev.twitch.tv/console/apps (category: Application
// Integration, OAuth redirect: http://localhost). Responses are cached in scripts/.cache/; delete that
// folder to force a full refresh. A cold run takes roughly an hour (Steam rate limits).
const fs = require('node:fs');
const path = require('node:path');
const config = require('./config.js');
const { selectGames, buildEntry, steamAppId, demoteBroadTags, developerCompanyIds } = require('./transform.js');
const { createCache, getTwitchToken, fetchIgdbCandidates, fetchCompanies, fetchSteamData } = require('./sources.js');

const ROOT = path.join(__dirname, '..');
const POOL_SIZE = 3000;
const CANDIDATES = 5000;

function renderDataJs(games, dateStr) {
  return `// GENERATED by scripts/build-data.js on ${dateStr} — do not edit by hand.\n`
    + `const GAMES = [\n${games.map(g => JSON.stringify(g)).join(',\n')}\n];\n`
    + `if (typeof module !== 'undefined') module.exports = GAMES;\n`;
}

function renderExcluded(excluded) {
  return '# id\tname\treason  (move games back with forceInclude in scripts/config.js)\n'
    + excluded.map(e => `${e.id}\t${e.name}\t${e.reason}\n`).join('');
}

function pct(n, total) { return total ? `${Math.round((n / total) * 100)}%` : '0%'; }

async function main() {
  const clientId = process.env.TWITCH_CLIENT_ID;
  const clientSecret = process.env.TWITCH_CLIENT_SECRET;
  if (!clientId || !clientSecret) {
    console.error('Missing TWITCH_CLIENT_ID / TWITCH_CLIENT_SECRET environment variables. See header of scripts/build-data.js.');
    process.exit(1);
  }

  const cache = createCache(path.join(__dirname, '.cache'));
  const token = await getTwitchToken(clientId, clientSecret);
  const raws = await fetchIgdbCandidates({ clientId, token, cache, total: CANDIDATES });
  const { kept, excluded } = selectGames(raws, config, POOL_SIZE);
  const companies = await fetchCompanies(kept.flatMap(developerCompanyIds), { clientId, token, cache });
  console.log(`Companies: ${companies.size} (developers + parent chains)`);

  const unmapped = new Map();
  const onUnmapped = name => unmapped.set(name, (unmapped.get(name) || 0) + 1);
  let games = [];
  let withSteamTags = 0;

  for (const [i, raw] of kept.entries()) {
    const appId = steamAppId(raw);
    let steam = { tags: null, metacritic: null };
    if (appId) {
      steam = await fetchSteamData(appId, { cache });
      if (steam.failed) console.warn(`  Steam fetch failed for ${raw.name} (app ${appId}); using IGDB fallback`);
    }
    const entry = buildEntry(raw, steam, config, onUnmapped, companies);
    if (!entry.primaryTags.length) { excluded.push({ id: raw.id, name: raw.name, reason: 'no tags' }); continue; }
    if (steam.tags && steam.tags.length) withSteamTags++;
    games.push(entry);
    if ((i + 1) % 100 === 0) console.log(`Enriched ${i + 1}/${kept.length}`);
  }

  const { games: demotedGames, demoted } = demoteBroadTags(games, config.broadTagThreshold);
  games = demotedGames;
  games.sort((a, b) => a.name.localeCompare(b.name) || a.year - b.year);
  const today = new Date().toISOString().slice(0, 10);
  fs.writeFileSync(path.join(ROOT, 'data.js'), renderDataJs(games, today));
  fs.writeFileSync(path.join(ROOT, 'excluded.txt'), renderExcluded(excluded));

  const byReason = {};
  for (const e of excluded) {
    const reason = e.reason.split(':')[0].replace(/ of \d+$/, '');
    byReason[reason] = (byReason[reason] || 0) + 1;
  }
  console.log('\n── Summary ──');
  console.log(`Kept: ${games.length}`);
  console.log(`Excluded: ${excluded.length}`, byReason);
  console.log(`With Steam tags: ${pct(withSteamTags, games.length)}`);
  console.log(`Broad tags demoted to secondary: ${demoted.join(', ') || 'none'}`);
  console.log(`Null metacritic: ${pct(games.filter(g => g.metacritic == null).length, games.length)}`);
  if (unmapped.size) console.log('Unmapped platforms (add to platformMap?):', Object.fromEntries(unmapped));
}

if (require.main === module) {
  main().catch(err => { console.error(err.message); process.exit(1); });
}

module.exports = { renderDataJs, renderExcluded };
